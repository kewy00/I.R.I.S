const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('irisOS', {
  isElectron: true,
  askAI: (prompt) => ipcRenderer.invoke('iris:ask-ai', prompt),
  loadHistory: () => ipcRenderer.invoke('iris:load-history'),
  saveHistory: (messages) => ipcRenderer.invoke('iris:save-history', messages),
  getSettings: () => ipcRenderer.invoke('iris:get-settings'),
  updateSettings: (updates) => ipcRenderer.invoke('iris:update-settings', updates),
  listOllamaModels: () => ipcRenderer.invoke('iris:list-ollama-models'),
  executeArtifactAction: (payload) => ipcRenderer.invoke('iris:artifact-action', payload),
  spotifyStatus: () => ipcRenderer.invoke('iris:spotify-status'),
  spotifyNowPlaying: () => ipcRenderer.invoke('iris:spotify-now-playing'),
  spotifyControl: (action, volumePercent) =>
    ipcRenderer.invoke('iris:spotify-control', volumePercent !== undefined ? { action, volumePercent } : action),
  spotifySeek: (positionMs) => ipcRenderer.invoke('iris:spotify-seek', positionMs),
  spotifyPlaylists: () => ipcRenderer.invoke('iris:spotify-playlists'),
  spotifyAddToPlaylist: (payload) => ipcRenderer.invoke('iris:spotify-add-to-playlist', payload),
  spotifyOpenTrack: (uri) => ipcRenderer.invoke('iris:spotify-open-track', uri),
  spotifyConnect: (clientId) => ipcRenderer.invoke('iris:spotify-connect', clientId),
  spotifyDisconnect: () => ipcRenderer.invoke('iris:spotify-disconnect'),
  listIntegrations: () => ipcRenderer.invoke('iris:list-integrations'),
  connectIntegration: (serviceId, credentials) => ipcRenderer.invoke('iris:connect-integration', { serviceId, credentials }),
  disconnectIntegration: (serviceId) => ipcRenderer.invoke('iris:disconnect-integration', serviceId),
  onBackgroundReply: (cb) => ipcRenderer.on('iris:background-reply', (_event, data) => cb(data)),
  getSystemStats: () => ipcRenderer.invoke('iris:get-system-stats'),
  openApp: (query) => ipcRenderer.invoke('iris:open-app', query),
  inspectScreen: () => ipcRenderer.invoke('iris:inspect-screen'),
  runAction: (action) => ipcRenderer.invoke('iris:run-action', action),
  resizeWindow: (width, height) => ipcRenderer.send('iris:resize-window', { width, height }),
  onShortcutWake: (cb) => ipcRenderer.on('iris:shortcut-wake', (_event, payload) => cb(payload || {})),
  triggerHotkeyWake: () => ipcRenderer.send('iris:hotkey-wake'),
  hideToBackground: () => ipcRenderer.send('iris:hide-to-background'),
  autoHideAfterTurn: () => ipcRenderer.send('iris:auto-hide-after-turn'),
  setBackgroundMode: (enabled) => ipcRenderer.send('iris:set-background-mode', Boolean(enabled)),
  onBackgroundModeSync: (cb) => ipcRenderer.on('iris:background-mode-sync', (_event, enabled) => cb(Boolean(enabled))),
  setDndMode: (enabled) => ipcRenderer.send('iris:set-dnd-mode', Boolean(enabled)),
  onDndModeSync: (cb) => ipcRenderer.on('iris:dnd-mode-sync', (_event, enabled) => cb(Boolean(enabled))),
  setCompactState: (state) => ipcRenderer.send('iris:set-compact-state', state),
  setAutoStart: (enabled) => ipcRenderer.invoke('iris:set-autostart', Boolean(enabled)),
  onAutoStartSync: (cb) => ipcRenderer.on('iris:autostart-sync', (_event, enabled) => cb(Boolean(enabled)))
});
